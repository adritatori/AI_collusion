"""Large-sample per-case flag rates for the JS statistical parity test (SPEC 6.3, revised).
exp1.json is one 200-episode sample per case, so it is too noisy to test a port against.
This writes counts from 4000 episodes per case (default settings, frozen exp1 thresholds)."""
import json, os, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from sim import CASES, episode
from detectors import all_scores, plus_factor

ROOT = os.path.join(HERE, "..", "..")
SEED, N_EP = 20251025, 4000
exp1 = json.load(open(os.path.join(ROOT, "data", "exp1.json")))
TH, TH_PF = exp1["thresholds"], exp1["plus_factor_thresholds"]

rng = np.random.default_rng(SEED)
cases = {}
for c in CASES:
    rows = [all_scores(episode(c, rng)) for _ in range(N_EP)]
    counts = {k: int(sum(r[k] > TH[k] for r in rows)) for k in TH}
    counts["plus_factor"] = int(sum(plus_factor(r, TH_PF) for r in rows))
    cases[c] = dict(counts=counts, rates={k: v / N_EP for k, v in counts.items()})
    print(c, cases[c]["rates"])
json.dump(dict(note="Per-case flag counts from the Python reference, default settings (N=4, T=30), "
                    "frozen exp1 thresholds. Generated by reference/python/make_statistical_reference.py.",
               seed=SEED, n_per_case=N_EP, thresholds=TH, plus_factor_thresholds=TH_PF, cases=cases),
          open(os.path.join(ROOT, "fixtures", "statistical_reference.json"), "w"), indent=1)
